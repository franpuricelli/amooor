// build-template-media.mjs — (re)write lib/photos.ts, the photo manifest.
//
// EN · The template ships ONE set of blank placeholders (public/_blank/*.jpg) in
//      three aspect ratios, shared by every empty slot — so the repo carries six
//      images, not thousands of identical copies. This writes lib/photos.ts: the
//      per-category slug lists plus resolvers that send each slot to the right
//      shared blank, OR to your own photo when you drop one at
//      public/photos/<category>/<slug>.jpg (+ public/thumbs/<category>/<slug>.jpg).
//      Add your files, re-run this, and those slots switch to your images.
// ES · La plantilla trae UN set de placeholders en blanco (public/_blank/*.jpg)
//      en tres proporciones, compartido por cada slot vacío — así el repo lleva
//      seis imágenes, no miles de copias idénticas. Esto escribe lib/photos.ts:
//      las listas de slugs por categoría más resolvers que mandan cada slot al
//      blanco compartido, O a tu propia foto cuando dejás una en
//      public/photos/<categoría>/<slug>.jpg (+ public/thumbs/<categoría>/<slug>.jpg).
//      Agregá tus archivos, re-corré esto, y esos slots pasan a tus imágenes.
//
// Run: node tools/gen-placeholders.mjs && node tools/build-template-media.mjs
import { existsSync, writeFileSync } from "node:fs";

// [slug, count] — order = order on the site. Counts mirror the original layout
// so grids look full. Edit freely.
const CATEGORIES = [
  ["how-we-met", 1],
  ["graduation", 9],
  ["first-year", 18],
  ["valentines", 21],
  ["moving-in", 15],
  ["dinners", 24],
  ["trip-one", 26],
  ["trip-two", 38],
  ["trip-three", 66],
  ["trip-four", 35],
  ["trip-five", 33],
  ["anniversaries", 6],
  ["big-win", 6],
  ["costumes", 3],
  ["little-things", 57],
  ["everything-else", 110],
];

const manifest = {};
const real = []; // "cat/slug" slots that already have a real photo committed
let total = 0;

CATEGORIES.forEach(([cat, count]) => {
  const width = Math.max(2, String(count).length);
  const slugs = [];
  for (let i = 1; i <= count; i++) {
    const slug = String(i).padStart(width, "0");
    slugs.push(slug);
    // A real photo at the documented path takes over that slot; otherwise the
    // slot falls back to a shared blank (resolved in lib/photos.ts).
    if (existsSync(`public/photos/${cat}/${slug}.jpg`)) real.push(`${cat}/${slug}`);
  }
  manifest[cat] = slugs;
  total += count;
});

const body = Object.entries(manifest)
  .map(
    ([cat, slugs]) =>
      `  "${cat}": [\n${slugs.map((s) => `    "${s}"`).join(",\n")}\n  ]`
  )
  .join(",\n");

const realBody = real.map((k) => `  "${k}"`).join(",\n");

const out = `// AUTO-GENERATED by tools/build-template-media.mjs — do not edit by hand.
// EN · ${total} photo slots across ${CATEGORIES.length} categories. Empty slots share the
//      three blank placeholders in /public/_blank; drop a file at
//      /public/photos/<category>/<slug>.jpg (+ /public/thumbs/...) and re-run the
//      build script to give that slot your own image.
// ES · ${total} slots de fotos en ${CATEGORIES.length} categorías. Los slots vacíos comparten
//      los tres placeholders en /public/_blank; dejá un archivo en
//      /public/photos/<categoría>/<slug>.jpg (+ /public/thumbs/...) y re-corré el
//      script para que ese slot use tu propia imagen.

export const photosByCategory: Record<string, string[]> = {
${body}
};

export interface CatPhoto {
  cat: string;
  slug: string;
}

/** Every photo, in category order — drives the full gallery. */
export const allPhotos: CatPhoto[] = Object.entries(photosByCategory).flatMap(
  ([cat, slugs]) => slugs.map((slug) => ({ cat, slug }))
);

export const totalPhotos = ${total};

import { BASE } from "./base";

// Slots with a real photo committed at /public/photos/<cat>/<slug>.jpg.
const REAL = new Set<string>([
${realBody}
]);

const CATS = Object.keys(photosByCategory);
const VARIANTS = ["a", "b", "c"]; // portrait / square / landscape

// Each theme has its own tinted blank set (romantic = rose, editorial = greige,
// brutalist = paper + ink frame); NEXT_PUBLIC_THEME picks the matching suffix.
const BLANK_BY_THEME: Record<string, string> = { editorial: "-editorial", brutalist: "-brutalist" };
const BLANK = BLANK_BY_THEME[process.env.NEXT_PUBLIC_THEME ?? "romantic"] ?? "";

// Deterministic aspect mix (offset per category so columns vary) — picks which
// of the three shared blanks a still-empty slot shows.
function variant(cat: string, slug: string): string {
  const ci = CATS.indexOf(cat);
  const i = photosByCategory[cat]?.indexOf(slug) ?? -1;
  return VARIANTS[((i + 1) + ci) % VARIANTS.length];
}

export const photos = (cat: string): string[] => photosByCategory[cat] ?? [];
export const thumb = (cat: string, slug: string) =>
  REAL.has(\`\${cat}/\${slug}\`)
    ? \`\${BASE}/thumbs/\${cat}/\${slug}.jpg\`
    : \`\${BASE}/_blank/thumb-\${variant(cat, slug)}\${BLANK}.jpg\`;
export const full = (cat: string, slug: string) =>
  REAL.has(\`\${cat}/\${slug}\`)
    ? \`\${BASE}/photos/\${cat}/\${slug}.jpg\`
    : \`\${BASE}/_blank/full-\${variant(cat, slug)}\${BLANK}.jpg\`;
`;

writeFileSync("lib/photos.ts", out);
console.log(
  `wrote lib/photos.ts — ${total} slots, ${real.length} real photo(s), across ${CATEGORIES.length} categories`
);
