// build-template-media.mjs — regenerate the template's photo folders + manifest.
//
// EN · Wipes /public/photos + /public/thumbs, recreates one folder per category
//      with N blank placeholders (01.jpg, 02.jpg, …), and writes lib/photos.ts.
//      To use the template: replace these blanks with your own images (same
//      names) or just drop your photos in and rename accordingly.
// ES · Borra /public/photos + /public/thumbs, recrea una carpeta por categoría
//      con N placeholders en blanco (01.jpg, 02.jpg, …) y escribe lib/photos.ts.
//      Para usar la plantilla: reemplazá estos blancos por tus imágenes (mismos
//      nombres) o poné tus fotos y renombralas.
//
// Run: node tools/build-template-media.mjs
import { rmSync, mkdirSync, copyFileSync, writeFileSync } from "node:fs";

// [slug, count] — order = order they appear on the site. Counts mirror the
// original layout so the grids look full. Edit freely.
const CATEGORIES = [
  ["how-we-met", 1],
  ["graduation", 9],
  ["first-year", 18],
  ["valentines", 21],
  ["moving-in", 15],
  ["dinners", 24],
  ["trip-one", 26],
  ["trip-two", 38],
  ["trip-three", 66],
  ["trip-four", 35],
  ["trip-five", 33],
  ["anniversaries", 6],
  ["big-win", 6],
  ["costumes", 3],
  ["little-things", 57],
  ["everything-else", 110],
];

const FULL = "tools/_blank/full.jpg";
const THUMB = "tools/_blank/thumb.jpg";

rmSync("public/photos", { recursive: true, force: true });
rmSync("public/thumbs", { recursive: true, force: true });

const manifest = {};
let total = 0;

for (const [cat, count] of CATEGORIES) {
  mkdirSync(`public/photos/${cat}`, { recursive: true });
  mkdirSync(`public/thumbs/${cat}`, { recursive: true });
  const width = Math.max(2, String(count).length);
  const slugs = [];
  for (let i = 1; i <= count; i++) {
    const slug = String(i).padStart(width, "0");
    slugs.push(slug);
    copyFileSync(FULL, `public/photos/${cat}/${slug}.jpg`);
    copyFileSync(THUMB, `public/thumbs/${cat}/${slug}.jpg`);
  }
  manifest[cat] = slugs;
  total += count;
}

const body = Object.entries(manifest)
  .map(
    ([cat, slugs]) =>
      `  "${cat}": [\n${slugs.map((s) => `    "${s}"`).join(",\n")}\n  ]`
  )
  .join(",\n");

const out = `// AUTO-GENERATED by tools/build-template-media.mjs — do not edit by hand.
// EN · One folder per category in /public/photos + /public/thumbs.
//      ${total} blank placeholder photos across ${CATEGORIES.length} categories.
// ES · Una carpeta por categoría en /public/photos + /public/thumbs.
//      ${total} fotos placeholder en blanco en ${CATEGORIES.length} categorías.

export const photosByCategory: Record<string, string[]> = {
${body}
};

export interface CatPhoto {
  cat: string;
  slug: string;
}

/** Every photo, in category order — drives the full gallery. */
export const allPhotos: CatPhoto[] = Object.entries(photosByCategory).flatMap(
  ([cat, slugs]) => slugs.map((slug) => ({ cat, slug }))
);

export const totalPhotos = ${total};

export const photos = (cat: string): string[] => photosByCategory[cat] ?? [];
export const thumb = (cat: string, slug: string) => \`/thumbs/\${cat}/\${slug}.jpg\`;
export const full = (cat: string, slug: string) => \`/photos/\${cat}/\${slug}.jpg\`;
`;

writeFileSync("lib/photos.ts", out);
console.log(`wrote lib/photos.ts — ${total} photos across ${CATEGORIES.length} categories`);
