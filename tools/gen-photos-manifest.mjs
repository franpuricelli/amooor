// gen-photos-manifest.mjs — regenerate lib/photos.ts from tools/categorized-index.tsv.
// Run after tools/build-categorized.sh:  node tools/gen-photos-manifest.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const rows = readFileSync(join(root, "tools/categorized-index.tsv"), "utf8")
  .trim()
  .split("\n")
  .map((l) => l.split("\t"));

const byCat = {};
for (const [cat, slug] of rows) (byCat[cat] ??= []).push(slug);

const total = rows.length;
const out = `// AUTO-GENERATED by tools/gen-photos-manifest.mjs — do not edit by hand.
// One folder per event in ~/Downloads/Fotos aniversario -> one category here.
// ${total} photos across ${Object.keys(byCat).length} categories.

export const photosByCategory: Record<string, string[]> = ${JSON.stringify(byCat, null, 2)};

export interface CatPhoto {
  cat: string;
  slug: string;
}

/** Every photo (${total}) in category order — drives the full gallery. */
export const allPhotos: CatPhoto[] = Object.entries(photosByCategory).flatMap(
  ([cat, slugs]) => slugs.map((slug) => ({ cat, slug }))
);

export const totalPhotos = ${total};

export const photos = (cat: string): string[] => photosByCategory[cat] ?? [];
export const thumb = (cat: string, slug: string) => \`/thumbs/\${cat}/\${slug}.jpg\`;
export const full = (cat: string, slug: string) => \`/photos/\${cat}/\${slug}.jpg\`;
`;

writeFileSync(join(root, "lib/photos.ts"), out);
console.log(`lib/photos.ts: ${total} photos, ${Object.keys(byCat).length} categories`);
