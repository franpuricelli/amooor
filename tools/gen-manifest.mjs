// Validate & warn on any curated slug missing from thumbs
const rows = [];
for (const [chapter, slugs] of Object.entries(chapters)) {
  slugs.forEach((slug, i) => {
    if (!allSet.has(slug)) { console.warn(`  ⚠ missing thumb: ${slug} (${chapter})`); return; }
    const pool = captions[chapter];
    rows.push({ slug, chapter, caption: pool[i % pool.length] });
  });
}

const curatedSet = new Set(rows.map((r) => r.slug));
const missingHero = !allSet.has(hero);
const missingTrans = !allSet.has(transition);
if (missingHero) console.warn(`  ⚠ hero missing: ${hero}`);
if (missingTrans) console.warn(`  ⚠ transition missing: ${transition}`);

